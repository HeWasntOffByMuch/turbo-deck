/**
 * The body face: 6x10, printable ASCII (spec 123).
 *
 * The repo's existing font is 5x7 and has sixteen glyphs, because it was built
 * for damage numbers and a damage number is digits and a bang (spec 065). A
 * character sheet is read for hours, so it needs a face with a real lowercase --
 * which means descenders, which means rows below the baseline, which 5x7 does
 * not have.
 *
 * The grid is 6 wide by 10 tall: rows 0-6 are the cap band, row 7 is the
 * baseline's own row, and rows 8-9 are the descender. So `p` and `y` hang and
 * `o` and `n` do not, and the two faces still share the same rendering path
 * because a glyph is a list of `#` rows either way.
 *
 * Authored as text for the reason `pixel-font.ts` gives and this repo has held
 * to for sixty-odd specs: nothing may be fetched, and a font file is a binary
 * blob nobody can review in a diff. A table is editable in the diff that changes
 * it.
 *
 * Pure. No DOM, no clock.
 */

